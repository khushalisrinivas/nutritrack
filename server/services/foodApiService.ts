export async function searchFoodCatalog(query: string, filterType: 'all' | 'indian' | 'global' = 'all') {
  const clean = query.trim().toLowerCase();

  // 1. Search local curated database
  let matches = INDIAN_FOOD_DATABASE.filter((item) => {
    if (filterType === 'indian' && !item.isIndian) return false;
    if (filterType === 'global' && item.isIndian) return false;

    if (!clean) return true;
    return (
      item.name.toLowerCase().includes(clean) ||
      item.category.toLowerCase().includes(clean) ||
      item.description.toLowerCase().includes(clean)
    );
  });

  // Sort best matches first
  if (clean) {
    matches.sort((a, b) => {
      const aStarts = a.name.toLowerCase().startsWith(clean);
      const bStarts = b.name.toLowerCase().startsWith(clean);
      if (aStarts && !bStarts) return -1;
      if (!aStarts && bStarts) return 1;
      return 0;
    });
  }

  // 2. If query is specific and user asked for global/all, attempt USDA search if API available or query doesn't match Indian
  if (clean.length >= 3 && filterType !== 'indian') {
    try {
      const apiKey = process.env.USDA_API_KEY || 'DEMO_KEY';
      // Only call if we have fewer matches or specific search
      if (matches.length < 8) {
        const usdaRes = await axios.get('https://api.nal.usda.gov/fdc/v1/foods/search', {
          params: {
            query: clean,
            pageSize: 5,
            api_key: apiKey,
          },
          timeout: 2500,
        });

        if (usdaRes.data?.foods?.length) {
          const usdaFoods: FoodItemDefinition[] = usdaRes.data.foods.map((f: any, idx: number) => {
            const findNutrient = (nameOrId: string) => {
              const n = f.foodNutrients?.find((nut: any) =>
                nut.nutrientName?.toLowerCase().includes(nameOrId.toLowerCase())
              );
              return n ? Number(n.value) : 0;
            };

            const calories = findNutrient('energy') || 100;
            const protein = findNutrient('protein') || 0;
            const carbs = findNutrient('carbohydrate') || 0;
            const fat = findNutrient('total lipid') || 0;
            const fiber = findNutrient('fiber') || 0;

            return {
              id: `usda_${f.fdcId || idx}`,
              name: f.description || clean,
              category: 'Global / Fitness',
              isIndian: false,
              defaultServing: '1 serving (100g)',
              servingUnits: [
                { label: '1 serving (100g)', multiplier: 1.0 },
                { label: 'Half serving (50g)', multiplier: 0.5 },
                { label: 'Double serving (200g)', multiplier: 2.0 },
              ],
              baseCalories: Math.round(calories),
              baseProtein: Math.round(protein * 10) / 10,
              baseCarbs: Math.round(carbs * 10) / 10,
              baseFat: Math.round(fat * 10) / 10,
              baseFiber: Math.round(fiber * 10) / 10,
              imageEmoji: '🍽️',
              description: `USDA Verified: ${f.brandOwner || f.dataType || 'Standard Reference'}`,
            };
          });

          matches = [...matches, ...usdaFoods];
        }
      }
    } catch {
      // USDA API fallback gracefully without breaking local search
    }
  }

  return matches;
}

export function getFoodById(id: string): FoodItemDefinition | undefined {
  return INDIAN_FOOD_DATABASE.find((f) => f.id === id);
}
